test('password hashing, safe signup fields and ownership rules', async () => {
  const hash = await hashPassword('admin');
  assert.notEqual(hash, 'admin');
  assert.equal(await verifyPassword('admin', hash), true);
  assert.equal(await verifyPassword('wrong', hash), false);
  assert.throws(() => userFields({ username: 'new_admin', password: 'password123', role: 'admin' }, { creating: true }), /buyer or seller/);
  assert.throws(() => userFields({ role: 'admin' }), /Unrecognized/);
  assert.equal(canManage({ _id: 'seller1', role: 'seller' }, { sellerId: 'seller2' }), false);
  assert.equal(canView(null, { approval: 'waiting' }), false);
  assert.equal(canView({ _id: 'seller1', role: 'seller' }, { sellerId: 'seller1', approval: 'waiting' }), true);
});

test('account HTTP flow, admin login, role boundaries, profile and contact inbox', async (t) => {
  const accounts = new Map();
  const sessions = new Map();
  const inbox = [];
  const make = async (data) => {
    if (accounts.has(data.username)) throw Object.assign(new Error('duplicate'), { code: 11000 });
    const user = new User(data); await user.validate();
    user.save = async () => { await user.validate(); return user; };
    accounts.set(user.username, user); return user;
  };
  t.mock.method(User, 'init', async () => {});
  t.mock.method(User, 'exists', async ({ username }) => accounts.has(username));
  t.mock.method(User, 'create', make);
  t.mock.method(User, 'findOne', (filter) => ({ select: async () => {
    const user = accounts.get(filter.username);
    return user?.active ? user : null;
  } }));
  t.mock.method(User, 'findById', async (id) => [...accounts.values()].find((user) => user.id === String(id)) || null);
  t.mock.method(User, 'deleteOne', async ({ _id }) => {
    const user = [...accounts.values()].find((entry) => entry.id === String(_id));
    if (user) accounts.delete(user.username);
    return { deletedCount: user ? 1 : 0 };
  });
  t.mock.method(User, 'find', (filter) => ({ sort: async () => [...accounts.values()].filter((user) => !filter.role || user.role === filter.role) }));
  t.mock.method(Session, 'create', async (data) => { sessions.set(data.tokenHash, data); return data; });
  t.mock.method(Session, 'findOne', ({ tokenHash: key }) => ({ populate: async () => {
    const data = sessions.get(key);
    const user = data && [...accounts.values()].find((entry) => entry.id === String(data.userId));
    return user ? { userId: user } : null;
  } }));
  t.mock.method(Session, 'deleteOne', async ({ tokenHash: key }) => sessions.delete(key));
  t.mock.method(Session, 'deleteMany', async ({ userId }) => {
    for (const [key, session] of sessions) if (String(session.userId) === String(userId)) sessions.delete(key);
  });
  t.mock.method(Message, 'create', async (data) => { const message = new Message(data); await message.validate(); inbox.push(message); return message; });
  t.mock.method(Message, 'find', () => ({ sort: async () => inbox }));
  t.mock.method(mongoose.connection, 'transaction', async (callback) => callback({}));
  let item;
  t.mock.method(Auction, 'create', async (data) => { item = new Auction(data); await item.validate(); item.save = async () => item; return item; });
  t.mock.method(Auction, 'findById', async () => item);
  t.mock.method(Bid, 'exists', () => ({ session: async () => null }));
  t.mock.method(Payment, 'exists', () => ({ session: async () => null }));
  await ensureDemoAdmin();
  const seededHash = accounts.get('admin').passwordHash;
  await ensureDemoAdmin();
  assert.equal(accounts.get('admin').passwordHash, seededHash);
  const server = app.listen(0, '127.0.0.1');
  await new Promise((resolve) => server.once('listening', resolve));
  t.after(() => new Promise((resolve) => server.close(resolve)));
  const base = `http://127.0.0.1:${server.address().port}/api`;
  async function request(path, method = 'GET', body, cookie, origin) {
    const response = await fetch(base + path, { method, headers: { 'Content-Type': 'application/json', ...(cookie && { Cookie: cookie }), ...(origin && { Origin: origin }) }, ...(body !== undefined && { body: JSON.stringify(body) }) });
    return { status: response.status, body: await response.json(), cookie: response.headers.get('set-cookie')?.split(';')[0], rawCookie: response.headers.get('set-cookie') };
  }
  assert.equal((await request('/health')).status, 200);
  assert.equal((await request('/auth/me')).body.data, null);
  assert.equal((await request('/admin/users')).status, 401);
  assert.equal((await request('/auth/login','POST',{ username: 'admin', password: 'wrong' })).status, 401);
  const admin = await request('/auth/login', 'POST', { username: 'admin', password: 'admin' });
  assert.equal(admin.status, 200);
  assert.match(admin.rawCookie, /HttpOnly/);
  assert.match(admin.rawCookie, /SameSite=Lax/);
  assert.equal(admin.body.data.role, 'admin');
  assert.equal('passwordHash' in admin.body.data, false);
  const profile = { firstName: 'Test', lastName: 'Person', email: 'test@example.com', contactNo: '0771234567', password: 'password123' };
  const buyer = await request('/auth/signup', 'POST', { ...profile, username: 'buyer1', role: 'buyer' });
  const seller = await request('/auth/signup', 'POST', { ...profile, username: 'seller1', role: 'seller' });
  assert.equal(buyer.status, 201); assert.equal(seller.status, 201);
  assert.equal((await request('/auth/signup','POST',{ ...profile, username: 'other', role: 'admin' })).status, 400);
  assert.equal((await request('/auth/signup','POST',{ ...profile, username: 'buyer1', role: 'buyer' })).status, 409);
  assert.equal((await request('/auth/signup','POST',{ ...profile, username: 'other', role: 'buyer', password: 'short' })).status, 400);
  assert.equal((await request('/admin/users','GET',undefined,buyer.cookie)).status, 403);
  assert.equal((await request('/admin/users','GET',undefined,seller.cookie)).status, 403);
  assert.equal((await request('/admin/users','GET',undefined,admin.cookie)).status, 200);
  assert.equal((await request('/uploads','POST',{ data: 'data:image/svg+xml;base64,AAAA' },seller.cookie)).status,400);
  assert.equal((await request('/uploads','POST',{ data: 'data:image/png;base64,AAAAAAAAAAAAAAAAAAAA' },seller.cookie)).status,400);
  assert.equal((await request('/uploads','POST',{},buyer.cookie)).status,403);
  assert.equal((await request('/auth/profile','PUT',{ role: 'admin' },buyer.cookie)).status, 400);
  assert.equal((await request('/auth/profile','PUT',{ firstName: 'Updated' },buyer.cookie)).body.data.firstName, 'Updated');
  assert.equal((await request('/auth/profile','PUT',{ firstName: 'Bad origin' },buyer.cookie,'https://example.org')).status, 403);
  assert.equal((await request('/auctions','POST',{},buyer.cookie)).status, 403);
  const created = await request('/auctions','POST',{ title: 'Test item', description: 'Test description', category: 'Watches', startingPrice: 10, endsAt: new Date(Date.now()+60000).toISOString() },seller.cookie);
  assert.equal(created.status, 201);
  assert.equal(created.body.data.approval, 'waiting');
  assert.equal(created.body.data.sellerId, seller.body.data._id);
  assert.equal((await request(`/auctions/${item.id}`)).status, 404);
  assert.equal((await request(`/auctions/${item.id}/bids`,'POST',{amount:20},seller.cookie)).status, 403);
  assert.equal((await request(`/auctions/${item.id}/approval`,'PATCH',{approval:'approved'},seller.cookie)).status, 403);
  assert.equal((await request(`/auctions/${item.id}/approval`,'PATCH',{approval:'approved'},admin.cookie)).status, 200);
  assert.equal((await request(`/auctions/${item.id}`)).status, 200);
  assert.equal((await request('/messages','POST',{ name: 'Buyer', email: 'test@example.com', subject: 'Help', message: 'Please help' },buyer.cookie)).status, 201);
  assert.equal((await request('/admin/messages','GET',undefined,admin.cookie)).body.data.length, 1);
  assert.equal((await request(`/admin/users/${admin.body.data._id}`,'DELETE',undefined,admin.cookie)).status, 409);
  const disposable = await request('/auth/signup','POST',{ ...profile, username: 'disposable', role: 'buyer' });
  const deletePath = `/admin/users/${disposable.body.data._id}`;
  assert.equal((await request(deletePath,'DELETE')).status,401);
  assert.equal((await request(deletePath,'DELETE',undefined,buyer.cookie)).status,403);
  const deleted = await request(deletePath,'DELETE',undefined,admin.cookie);
  assert.equal(deleted.status,200);
  assert.match(deleted.body.message,/deleted/);
  assert.equal(accounts.has('disposable'),false);
  assert.equal((await request('/admin/users','GET',undefined,admin.cookie)).body.data.some((user) => user._id === disposable.body.data._id),false);
  assert.equal((await request('/auth/me','GET',undefined,disposable.cookie)).body.data,null);
  assert.equal((await request('/auth/login','POST',{username:'disposable',password:profile.password})).status,401);
  assert.equal((await request(deletePath,'DELETE',undefined,admin.cookie)).status,404);
  assert.equal((await request('/admin/users/invalid','DELETE',undefined,admin.cookie)).status,400);
  assert.equal((await request('/auth/signup','POST',{ ...profile, username: 'disposable', role: 'buyer' })).status,201);
  const loggedOut = await request('/auth/logout','POST',undefined,buyer.cookie);
  assert.equal(loggedOut.status, 200);
  assert.equal(sessions.has(tokenHash(buyer.cookie.split('=')[1])), false);
  assert.equal((await request('/auth/me','GET',undefined,buyer.cookie)).body.data, null);
});
